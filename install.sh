#!/usr/bin/env bash
# Stegano Tool installer - works on Termux, Linux and macOS.
# Installs a `STEG` (and `steg`) launcher that runs the package with -m,
# so relative imports resolve no matter where it is called from.
set -eu

ROOT=$(cd "$(dirname "$0")" && pwd)

# 1. find a Python 3 interpreter
PY=""
for cand in python3 python; do
  if command -v "$cand" >/dev/null 2>&1; then
    if "$cand" -c 'import sys; sys.exit(0 if sys.version_info >= (3,8) else 1)' 2>/dev/null; then
      PY=$(command -v "$cand")
      break
    fi
  fi
done
if [ -z "$PY" ]; then
  echo "Error: Python 3.8+ not found." >&2
  echo "  Termux: pkg install python" >&2
  echo "  Debian/Ubuntu: sudo apt install python3" >&2
  echo "  macOS: brew install python3" >&2
  exit 1
fi

# 2. choose a bin directory that is (or can be) on PATH
if [ -n "${PREFIX:-}" ] && [ -d "${PREFIX}/bin" ]; then
  BIN="${PREFIX}/bin"            # Termux
else
  BIN="${HOME}/.local/bin"
fi
mkdir -p "$BIN"

# 3. write the launcher
LAUNCHER="$BIN/STEG"
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env bash
# Stegano Tool launcher (generated by install.sh)
export PYTHONPATH="$ROOT\${PYTHONPATH:+:\$PYTHONPATH}"
exec "$PY" -m stegano.cli "\$@"
EOF
chmod +x "$LAUNCHER"
ln -sf "$LAUNCHER" "$BIN/steg" 2>/dev/null || cp "$LAUNCHER" "$BIN/steg"

# 4. make sure BIN is on PATH for common shells
case ":${PATH}:" in
  *":$BIN:"*) ;;
  *)
    LINE="export PATH=\"$BIN:\$PATH\""
    for rc in "$HOME/.bashrc" "$HOME/.zshrc" "$HOME/.profile"; do
      [ -e "$rc" ] || continue
      grep -F "$BIN" "$rc" >/dev/null 2>&1 || printf '\n# Stegano Tool\n%s\n' "$LINE" >> "$rc"
    done
    [ -e "$HOME/.bashrc" ] || printf '# Stegano Tool\n%s\n' "$LINE" >> "$HOME/.bashrc"
    echo "Added $BIN to PATH in your shell profile."
    ;;
esac

# 5. fish users get a function too
if [ -d "$HOME/.config/fish" ]; then
  mkdir -p "$HOME/.config/fish/functions"
  printf 'function STEG\n    env PYTHONPATH="%s" %s -m stegano.cli $argv\nend\n' "$ROOT" "$PY" \
    > "$HOME/.config/fish/functions/STEG.fish"
fi

echo
echo "Stegano Tool installed."
echo "  launcher : $LAUNCHER"
echo "  python   : $PY"
echo "Restart the terminal or run: source ~/.bashrc"
echo "Then run: STEG --version   (or: STEG menu)"
echo
echo "Pipe examples:"
echo "  cat secret.zip | STEG hide photo.png - -o out.png"
echo "  STEG extract out.png -o - > secret.zip"
